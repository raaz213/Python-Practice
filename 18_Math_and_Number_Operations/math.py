import math

print("Square root of 16 is:", math.sqrt(16)) # Find the square root of 16 
print("Factorial of 5 is:", math.factorial(5)) # Find the factorial of 5
print("Value of pi is:", math.pi) # Find the value of pi
print("Value of e is:", math.e) # Find the value of e
print("Sine of 90 degrees is:", math.sin(math.radians(90))) # Find the sine of 90 degrees
print("Cosine of 0 degrees is:", math.cos(math.radians(0))) # Find the cosine of 0 degrees
print("Tangent of 45 degrees is:", math.tan(math.radians(45))) # Find the tangent of 45 degrees
print("Logarithm base 10 of 1000 is:", math.log10(1000)) # Find the logarithm base 10 of 1000
print("Logarithm base e of 20 is:", math.log(20)) # Find the logarithm base e of 20
print("Greatest common divisor of 48 and 180 is:", math.gcd(48, 180)) # Find the greatest common divisor of 48 and 180
print("Least common multiple of 12 and 15 is:", math.lcm(12, 15)) # Find the least common multiple of 12 and 15
print("Absolute value of -7 is:", math.fabs(-7)) # Find the absolute value of -7
print("Ceiling of 4.2 is:", math.ceil(4.2)) # Round 4.2 up to the nearest integer
print("Floor of 4.8 is:", math.floor(4.8)) # Round 4.8 down to the nearest integer
print("Power of 2 raised to 3 is:", math.pow(2, 3)) # Find the power of 2 raised to 3
